import AppKit

struct ClipActivity {
    enum Kind { case text(String), image(NSImage?), sensitive, code(String) }
    let toPhone: Bool
    let kind: Kind
    var date = Date()
    var file: URL? = nil
}

/// Vigila el portapapeles del Mac y aplica lo que llega del celular, sin rebotes.
final class ClipboardSync {
    private let link: PhoneLink
    private let pb = NSPasteboard.general
    private var lastChange: Int
    private var timer: Timer?
    private var lastFromPhoneKey: String?
    var enabled = true
    var onActivity: ((ClipActivity) -> Void)?

    private static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private static let maxImage = 25 * 1024 * 1024

    init(link: PhoneLink) {
        self.link = link
        lastChange = NSPasteboard.general.changeCount
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.35, repeats: true) { [weak self] _ in self?.poll() }
        timer?.tolerance = 0.1
    }

    // MARK: Mac → celular

    private func poll() {
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard enabled, link.isConnected else { return }
        let types = pb.types ?? []
        if types.contains(Self.transient) || types.contains(Self.autoGenerated) { return }

        // Archivos copiados en Finder: no son portapapeles de contenido
        if types.contains(.fileURL), pb.string(forType: .string) == nil { return }

        if let png = imagePNG(types: types) {
            if key(png) == lastFromPhoneKey { return }
            link.sendImage(png: png)
            onActivity?(ClipActivity(toPhone: true, kind: .image(NSImage(data: png))))
            return
        }
        if let s = pb.string(forType: .string), !s.isEmpty {
            if "txt:" + s == lastFromPhoneKey { return }
            link.send(["t": "text", "d": s, "sensitive": types.contains(Self.concealed)])
            onActivity?(ClipActivity(toPhone: true, kind: types.contains(Self.concealed) ? .sensitive : .text(s)))
        }
    }

    private func imagePNG(types: [NSPasteboard.PasteboardType]) -> Data? {
        // Si hay texto además de imagen (p. ej. copiar de una web), priorizar el texto
        if pb.string(forType: .string) != nil { return nil }
        if let png = pb.data(forType: .png) { return png.count <= Self.maxImage ? png : nil }
        if let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]) {
            return png.count <= Self.maxImage ? png : nil
        }
        return nil
    }

    // MARK: celular → Mac

    func handle(_ msg: [String: Any]) {
        guard enabled else { return }
        switch msg["t"] as? String {
        case "text":
            guard let s = msg["d"] as? String else { return }
            pb.clearContents()
            if msg["sensitive"] as? Bool == true { pb.setString("", forType: Self.concealed) }
            pb.setString(s, forType: .string)
            lastFromPhoneKey = "txt:" + s
            lastChange = pb.changeCount
            onActivity?(ClipActivity(toPhone: false, kind: msg["sensitive"] as? Bool == true ? .sensitive : .text(s)))
        case "image":
            guard let b64 = msg["b64"] as? String, let data = Data(base64Encoded: b64) else {
                Log.info("imagen: base64 inválido"); return }
            guard let rep = NSBitmapImageRep(data: data),
                  let png = rep.representation(using: .png, properties: [:]),
                  let tiff = rep.representation(using: .tiff, properties: [:]) else {
                Log.info("imagen: formato no soportado (\(msg["mime"] ?? "?"))"); return }
            pb.clearContents()
            pb.declareTypes([.png, .tiff], owner: nil)
            let ok = pb.setData(png, forType: .png) && pb.setData(tiff, forType: .tiff)
            if !ok { Log.info("imagen: no se pudo escribir en el portapapeles") }
            lastFromPhoneKey = key(png)
            lastChange = pb.changeCount
            onActivity?(ClipActivity(toPhone: false, kind: .image(NSImage(data: png))))
        default: break
        }
    }

    /// Código de verificación del celular: al portapapeles del Mac como contenido sensible, sin rebotarlo.
    func copyCode(_ code: String) {
        pb.clearContents()
        pb.setString("", forType: Self.concealed)
        pb.setString(code, forType: .string)
        lastFromPhoneKey = "txt:" + code
        lastChange = pb.changeCount
        onActivity?(ClipActivity(toPhone: false, kind: .code(code)))
    }

    /// Foto o captura del celular directo al portapapeles (sin archivo), en su formato original + PNG si es liviana.
    func putImageData(_ data: Data, mime: String) {
        let item = NSPasteboardItem()
        let type = NSPasteboard.PasteboardType(mime == "image/png" ? "public.png" : mime == "image/heic" ? "public.heic" : "public.jpeg")
        item.setData(data, forType: type)
        let img = NSImage(data: data)
        if mime != "image/png", let rep = NSBitmapImageRep(data: data) {
            // Copia PNG para apps que no leen JPEG/HEIC (fotos de hasta ~12 MP; más grandes quedan solo en su formato)
            if data.count < 8_000_000, let png = rep.representation(using: .png, properties: [:]) { item.setData(png, forType: .png) }
        }
        pb.clearContents()
        pb.writeObjects([item])
        lastChange = pb.changeCount
        onActivity?(ClipActivity(toPhone: false, kind: .image(img)))
    }

    /// Foto o captura recién llegada del celular: queda en el portapapeles (archivo + imagen) sin rebotar.
    func putPhoto(_ url: URL, mime: String) {
        let item = NSPasteboardItem()
        item.setString(url.absoluteString, forType: .fileURL)
        if let data = try? Data(contentsOf: url) {
            let type = NSPasteboard.PasteboardType(mime == "image/png" ? "public.png" : mime == "image/heic" ? "public.heic" : "public.jpeg")
            item.setData(data, forType: type)
            if mime != "image/png", data.count < 8_000_000, let rep = NSBitmapImageRep(data: data),
               let png = rep.representation(using: .png, properties: [:]) { item.setData(png, forType: .png) }
        }
        pb.clearContents()
        pb.writeObjects([item])
        lastChange = pb.changeCount
        onActivity?(ClipActivity(toPhone: false, kind: .image(NSImage(contentsOf: url)), file: url))
    }

    private func key(_ d: Data) -> String { "img:\(d.count):\(d.prefix(4096).hashValue)" }
}
